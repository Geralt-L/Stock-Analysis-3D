# pooled Spearman IC (score vs fwd5)
def spearman(xs, ys):
    def rank(v):
        s = sorted(range(len(v)), key=lambda i: v[i]); r=[0]*len(v)
        for i,idx in enumerate(s): r[idx]=i+1
        return r
    rx, ry = rank(xs), rank(ys); n=len(xs)
    mx, my = sum(rx)/n, sum(ry)/n
    cov = sum((rx[i]-mx)*(ry[i]-my) for i in range(n))
    vx = sum((rx[i]-mx)**2 for i in range(n))**0.5
    vy = sum((ry[i]-my)**2 for i in range(n))**0.5
    return cov/(vx*vy) if vx*vy else 0
pool = [(r["score"], r["fwd5"]) for r in obs if r["fwd5"] is not None]
