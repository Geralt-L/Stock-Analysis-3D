def agg(rows, key):
    groups = {}
    for r in rows:
        groups.setdefault(r[key], []).append(r)
    out = []
    for g, rs in sorted(groups.items(), key=lambda x: str(x[0])):
        line = {"group":g,"n":len(rs)}
        for h in (1,3,5):
            vals = [r[f"fwd{h}"] for r in rs if r[f"fwd{h}"] is not None]
            if vals:
                line[f"fwd{h}_mean"] = round(sum(vals)/len(vals),2)
                line[f"fwd{h}_win%"] = round(100*sum(1 for v in vals if v>0)/len(vals),0)
        out.append(line)
    return out

